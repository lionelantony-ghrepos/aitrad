#!/usr/bin/env node
/**
 * Writes committed snapshots under docs/kb/generated from the current packages.
 * Typedoc/OpenAPI dumps can replace the catalog later without changing consumers of INDEX.md.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(repoRoot, "docs", "kb", "generated");

function readWorkspacePackages() {
  const ws = fs.readFileSync(path.join(repoRoot, "pnpm-workspace.yaml"), "utf8");
  const globs = [...ws.matchAll(/-\s+"([^"]+)"/g)].map((m) => m[1]);
  const dirs = [];
  for (const glob of globs) {
    if (glob.endsWith("/*")) {
      const parent = path.join(repoRoot, glob.slice(0, -2));
      if (!fs.existsSync(parent)) {
        continue;
      }
      for (const name of fs.readdirSync(parent)) {
        const pkgJson = path.join(parent, name, "package.json");
        if (fs.existsSync(pkgJson)) {
          dirs.push(path.join(parent, name));
        }
      }
    }
  }
  return dirs.sort();
}

function listTsSources(pkgDir) {
  const roots = ["src", "app", "lib", "components"]
    .map((d) => path.join(pkgDir, d))
    .filter((d) => fs.existsSync(d));
  const out = [];
  const walk = (dir) => {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, ent.name);
      if (ent.isDirectory()) {
        walk(p);
      } else if (
        (ent.name.endsWith(".ts") || ent.name.endsWith(".tsx")) &&
        !ent.name.endsWith(".test.ts") &&
        !ent.name.endsWith(".test.tsx")
      ) {
        out.push(path.relative(pkgDir, p).replaceAll("\\", "/"));
      }
    }
  };
  for (const root of roots) {
    walk(root);
  }
  return out.sort();
}

function schemaCatalog() {
  const schemasDir = path.join(repoRoot, "packages", "schemas", "src");
  const names = [];
  if (!fs.existsSync(schemasDir)) {
    return names;
  }
  for (const file of fs.readdirSync(schemasDir)) {
    if (!file.endsWith(".ts") || file.endsWith(".test.ts")) {
      continue;
    }
    const text = fs.readFileSync(path.join(schemasDir, file), "utf8");
    for (const m of text.matchAll(/export const (\w+Schema)\s*=/g)) {
      names.push(`${file}: ${m[1]}`);
    }
  }
  return names.sort();
}

function writeIfChanged(file, contents) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (prev === contents) {
    return false;
  }
  fs.writeFileSync(file, contents, "utf8");
  return true;
}

function main() {
  const packages = readWorkspacePackages();
  const pkgLines = [
    "# Package inventory",
    "",
    "Generated by `pnpm docs:generate`. Not a substitute for as-built PBI pages.",
    "",
  ];
  for (const dir of packages) {
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    const rel = path.relative(repoRoot, dir).replaceAll("\\", "/");
    pkgLines.push(`## ${pkg.name}`, "", `- Path: \`${rel}\``, `- Sources:`);
    const sources = listTsSources(dir);
    if (sources.length === 0) {
      pkgLines.push("  - _(none)_");
    } else {
      for (const s of sources) {
        pkgLines.push(`  - \`${s}\``);
      }
    }
    pkgLines.push("");
  }

  const schemaNames = schemaCatalog();
  const schemaLines = [
    "# `@meridian/schemas` catalog",
    "",
    "Exported `*Schema` bindings discovered by static scan. Full OpenAPI from Zod is deferred until DTO coverage is broader (add `zod-to-openapi` then). Typedoc for packages is deferred until public APIs stabilize.",
    "",
  ];
  if (schemaNames.length === 0) {
    schemaLines.push("_(no schemas found)_", "");
  } else {
    for (const n of schemaNames) {
      schemaLines.push(`- ${n}`);
    }
    schemaLines.push("");
  }

  const readme = [
    "# Generated reference",
    "",
    "Committed snapshots from `pnpm docs:generate`. Do not hand-edit; regenerate instead.",
    "",
    "| File | Contents |",
    "| --- | --- |",
    "| [packages.md](packages.md) | Workspace package inventory and `src` files |",
    "| [schemas-catalog.md](schemas-catalog.md) | Zod `*Schema` exports in `@meridian/schemas` |",
    "",
    "Engineering docs here are **not** part of PBI-023 news RAG.",
    "",
  ].join("\n");

  writeIfChanged(path.join(outDir, "README.md"), readme);
  writeIfChanged(path.join(outDir, "packages.md"), `${pkgLines.join("\n")}\n`);
  writeIfChanged(path.join(outDir, "schemas-catalog.md"), schemaLines.join("\n"));
  console.log("Wrote docs/kb/generated snapshots.");
}

main();
